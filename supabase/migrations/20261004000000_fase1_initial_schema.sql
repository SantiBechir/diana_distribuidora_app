-- 3. Función trigger para actualizar updated_at automáticamente
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------------------------
-- 4. Tabla: CLIENTES
-- ------------------------------------------------------------------------------
CREATE TABLE public.clientes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  nombre TEXT NOT NULL,
  cuil TEXT,
  direccion TEXT,
  telefono TEXT,
  mail TEXT,
  tipo TEXT NOT NULL CHECK (tipo IN ('Regular', 'Licitación')) DEFAULT 'Regular',
  notas TEXT,
  saldo_centavos BIGINT NOT NULL DEFAULT 0, -- >0 debe plata, <0 saldo a favor (crédito)
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_clientes_user_nombre ON public.clientes (user_id, nombre);
CREATE INDEX idx_clientes_user_cuil ON public.clientes (user_id, cuil);

CREATE TRIGGER tr_clientes_updated_at
BEFORE UPDATE ON public.clientes
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ------------------------------------------------------------------------------
-- 5. Tabla: PRODUCTOS
-- ------------------------------------------------------------------------------
CREATE TABLE public.productos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  nombre TEXT NOT NULL,
  descripcion TEXT,
  unidad TEXT NOT NULL CHECK (unidad IN ('Kg', 'Bolsa', 'Unidad')) DEFAULT 'Kg',
  precio_costo_centavos BIGINT NOT NULL DEFAULT 0 CHECK (precio_costo_centavos >= 0),
  precio_venta_centavos BIGINT NOT NULL DEFAULT 0 CHECK (precio_venta_centavos >= 0),
  activo BOOLEAN NOT NULL DEFAULT true, -- Permite archivar producto sin borrar historial
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_productos_user_nombre ON public.productos (user_id, nombre);
CREATE INDEX idx_productos_user_activo ON public.productos (user_id, activo);

CREATE TRIGGER tr_productos_updated_at
BEFORE UPDATE ON public.productos
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ------------------------------------------------------------------------------
-- 6. Tabla: PROVEEDORES
-- ------------------------------------------------------------------------------
CREATE TABLE public.proveedores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  nombre TEXT NOT NULL,
  direccion TEXT,
  telefono TEXT,
  saldo_centavos BIGINT NOT NULL DEFAULT 0, -- Deuda con el proveedor en centavos
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_proveedores_user_nombre ON public.proveedores (user_id, nombre);

CREATE TRIGGER tr_proveedores_updated_at
BEFORE UPDATE ON public.proveedores
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ------------------------------------------------------------------------------
-- 7. Tabla: PEDIDOS
-- ------------------------------------------------------------------------------
CREATE TABLE public.pedidos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  numero_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY,
  cliente_id UUID NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  total_centavos BIGINT NOT NULL DEFAULT 0 CHECK (total_centavos >= 0),
  total_costo_centavos BIGINT NOT NULL DEFAULT 0 CHECK (total_costo_centavos >= 0),
  estado TEXT NOT NULL CHECK (estado IN ('Impago', 'Pagado Parcialmente', 'Pagado', 'Cancelado')) DEFAULT 'Impago',
  notas TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_pedidos_user_cliente ON public.pedidos (user_id, cliente_id);
CREATE INDEX idx_pedidos_user_fecha ON public.pedidos (user_id, fecha DESC);
CREATE INDEX idx_pedidos_user_estado ON public.pedidos (user_id, estado);

CREATE TRIGGER tr_pedidos_updated_at
BEFORE UPDATE ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ------------------------------------------------------------------------------
-- 8. Tabla: PEDIDO_LINEAS
-- ------------------------------------------------------------------------------
CREATE TABLE public.pedido_lineas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  pedido_id UUID NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  producto_id UUID NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  proveedor_id UUID NOT NULL REFERENCES public.proveedores(id) ON DELETE RESTRICT,
  cantidad NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
  precio_unit_costo_centavos BIGINT NOT NULL CHECK (precio_unit_costo_centavos >= 0),
  precio_unit_venta_centavos BIGINT NOT NULL CHECK (precio_unit_venta_centavos >= 0),
  subtotal_costo_centavos BIGINT NOT NULL CHECK (subtotal_costo_centavos >= 0),
  subtotal_venta_centavos BIGINT NOT NULL CHECK (subtotal_venta_centavos >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_pedido_lineas_pedido ON public.pedido_lineas (pedido_id);
CREATE INDEX idx_pedido_lineas_producto ON public.pedido_lineas (producto_id);
CREATE INDEX idx_pedido_lineas_proveedor ON public.pedido_lineas (proveedor_id);

-- ------------------------------------------------------------------------------
-- 9. Tabla: PAGOS_CLIENTES (Relación obligatoria con pedido_id)
-- ------------------------------------------------------------------------------
CREATE TABLE public.pagos_clientes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  cliente_id UUID NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  pedido_id UUID NOT NULL REFERENCES public.pedidos(id) ON DELETE RESTRICT,
  monto_centavos BIGINT NOT NULL CHECK (monto_centavos > 0),
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  metodo_pago TEXT DEFAULT 'Efectivo',
  notas TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_pagos_clientes_user_cliente ON public.pagos_clientes (user_id, cliente_id);
CREATE INDEX idx_pagos_clientes_user_pedido ON public.pagos_clientes (user_id, pedido_id);

-- ------------------------------------------------------------------------------
-- 10. Tabla: PAGOS_PROVEEDORES (Relación obligatoria con proveedor_id)
-- ------------------------------------------------------------------------------
CREATE TABLE public.pagos_proveedores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  proveedor_id UUID NOT NULL REFERENCES public.proveedores(id) ON DELETE RESTRICT,
  monto_centavos BIGINT NOT NULL CHECK (monto_centavos > 0),
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  metodo_pago TEXT DEFAULT 'Efectivo',
  notas TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_pagos_proveedores_user_proveedor ON public.pagos_proveedores (user_id, proveedor_id);

